"""Grade the repaired helper and comparator against the pre-registration, beside the baseline.

Usage: python run_experiment.py OUTPUT_DIR
1. the five new cases with the baseline copy and the repaired helper;
2. the 27 old cases: baseline copy == committed entry, repaired == T(committed entry), and the
   old expectations re-graded unedited;
3. the 32 mutation controls with both comparators (mutated copies of the committed old
   results.json in a temporary directory that the script creates and removes itself).
Writes OUTPUT_DIR/results.json and OUTPUT_DIR/summary.md. Each check carries its result and
its pre-registered prediction; exit 1 if any result differs from its prediction (a finding).
Predicted failures (baseline defects, retained earlier failures) are kept and reported.
"""

import json
import sys
import tempfile
from pathlib import Path

import anchor_unit as repaired
import anchor_unit_baseline_7345bfe as baseline
import compare_results as cmp
import grading as g

SCRIPTS = g.ROOT / "scripts"
COMPARATORS = {"repaired": SCRIPTS / "compare_results.py", "baseline": SCRIPTS / "compare_results_baseline_7345bfe.py"}
USED = sorted(
    [
        "anchor_unit.py",
        "anchor_unit_baseline_7345bfe.py",
        "grading.py",
        "run_experiment.py",
        *(p.name for p in COMPARATORS.values()),
    ]
)


def global_checks():
    pairs = [
        ("context template unchanged", repaired.CONTEXT_TEMPLATE, g.EXP["context_template"]),
        ("budget bytes unchanged", repaired.BUDGET_BYTES, g.EXP["budget_bytes"]),
        ("budget scope as pre-registered", repaired.BUDGET_SCOPE, g.EXP["budget_scope"]),
        ("identity definitions as pre-registered", repaired.IDENTITIES, g.EXP["repaired_rules"]["R3_identities"]),
        (
            "environment exceptions as pre-registered",
            [list(p) for p in cmp.ENVIRONMENT_EXCEPTIONS],
            g.EXP["environment_exceptions"],
        ),
    ]
    return [
        g.check(name, g.strict_equal(got, want), "PASS", got if not g.strict_equal(got, want) else None)
        for name, got, want in pairs
    ]


def old_rows():
    rows = []
    for case, entry in g.old_cases():
        committed = {k: v for k, v in entry.items() if k not in ("case", "checks")}
        base = g.run_old_case(baseline, case, entry)
        out = g.run_old_case(repaired, case, entry)
        d_base = [[cmp.render(p), w] for p, w, _, _ in cmp.compare(cmp.as_json(base), committed, exceptions=())]
        d_rep = [[cmp.render(p), w] for p, w, _, _ in cmp.compare(cmp.as_json(out), g.transform_old(entry), exceptions=())]
        checks = [
            g.check("baseline copy output equals the committed entry", not d_base, "PASS", d_base),
            g.check("repaired output equals T(committed entry)", not d_rep, "PASS", d_rep),
            *g.old_regrade(case, out),
        ]
        rows.append({"case": case["id"], "inputs_root": g.EXP["old_inputs"]["root"], "output": out, "checks": checks})
    return rows


def mutation_rows():
    text = g.OLD_RESULTS.read_text(encoding="utf-8")
    committed = cmp.loads(text)
    rows = []
    with tempfile.TemporaryDirectory(prefix="evidence-integrity-mutations-") as tmp:
        for m in g.EXP["mutation_controls"]["mutations"]:
            mutated = g.mutate(text, m["ops"])
            path = Path(tmp) / f"{m['id']}.json"
            path.write_text(mutated, encoding="utf-8", newline="\n")
            permitted = m["repaired"] == "allowed"
            row = {"id": m["id"], "what": m["what"], "changes_text": mutated != text, "checks": []}
            for name, script in COMPARATORS.items():
                code, stderr, last = g.run_comparator(script, g.OLD_RESULTS, path)
                observed = g.classify(code, stderr, permitted)
                row[name] = {"exit": code, "observed": observed, "last_stderr_line": last if observed == "crash" else None}
                row["checks"].append(g.check(f"{name} comparator: {m[name]}", observed == m[name], "PASS", observed))
            try:
                paths = sorted({cmp.render(p) for p, *_ in cmp.compare(committed, cmp.loads(mutated))})
                row["repaired"]["paths"] = paths
            except cmp.InvalidJSONError as err:
                paths, row["repaired"]["paths"], row["repaired"]["invalid"] = None, None, str(err)
            if m["repaired_paths"] is not None:
                ok = paths == sorted(m["repaired_paths"])
                row["checks"].append(g.check("repaired comparator: difference paths as pre-registered", ok, "PASS", paths))
            rows.append(row)
    return rows


def summary_md(env, doc):
    lines = [
        "# Evidence-integrity results (generated by scripts/run_experiment.py)",
        "",
        (
            f"Python {sys.version.split()[0]}, {env['platform']}; lxml {env['lxml']}, libxml2 {env['libxml2_runtime']}. "
            "Each check has a result and a pre-registered prediction; a finding is a check whose result differs. "
            "Statuses are structural only; nothing was semantically reviewed."
        ),
        "",
        "## Totals",
        "",
        "| | count |",
        "|---|---|",
        *[f"| {k} | {v} |" for k, v in doc["summary"].items() if not isinstance(v, (list, dict))],
        "",
        "## New cases",
        "",
        "| case | anchor | helper | reasons | dom status | text status | diagnostics (line type) | encoding | failed requirements |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for row in doc["new_cases"]:
        o = row["output"]
        failed = [
            c["check"].split("requirement ")[-1]
            for c in row["checks"]
            if "requirement" in c["check"] and c["result"] == "FAIL"
        ]
        diags = ", ".join(f"{d['line']} {d['type']}" for d in o["parser"]["diagnostics"]) or "-"
        lines.append(
            f"| {row['case']} | `{o['anchor']}` | {row['helper']} | {', '.join(o['reasons']) or '-'}"
            f" | {o['status']['dom_serialization']} | {o['status']['text_content']} | {diags} | {o['parser']['encoding']}"
            f" | {', '.join(failed) or '-'} |"
        )
    lines += [
        "",
        "## Old cases (repaired helper)",
        "",
        "| case | reasons | dom status | text status | dom ctx B | text ctx B | failed checks (all predicted) |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in doc["old_cases"]:
        o = row["output"]
        failed = [c["check"] for c in row["checks"] if c["result"] == "FAIL"]
        ctx = o["contexts"]
        lines.append(
            f"| {row['case']} | {', '.join(o['reasons']) or '-'} | {o['status']['dom_serialization']} | {o['status']['text_content']}"
            f" | {ctx.get('dom_serialization', {}).get('context_bytes', '-')} | {ctx.get('text_content', {}).get('context_bytes', '-')}"
            f" | {'; '.join(failed) or '-'} |"
        )
    lines += ["", "## Mutation controls", "", "| id | mutation | repaired | baseline (7345bfe) |", "|---|---|---|---|"]
    lines += [
        f"| {r['id']} | {r['what']} | {r['repaired']['observed']} | {r['baseline']['observed']} |"
        for r in doc["mutation_controls"]
    ]
    return "\n".join(lines) + "\n"


def main():
    out_dir = Path(sys.argv[1])
    problems = g.verify_inputs()
    if problems:
        print("\n".join(problems))
        return 1
    new = []
    for b_row, r_row in zip(
        g.run_new_cases(baseline, "baseline", "baseline_fails"), g.run_new_cases(repaired, "repaired", None), strict=True
    ):
        new += [b_row, r_row]
    doc = {
        "environment": g.environment(repaired),
        "scripts_sha256": {p: g.sha256((SCRIPTS / p).read_bytes()) for p in USED},
        "identity_definitions": repaired.IDENTITIES,
        "budget_scope": repaired.BUDGET_SCOPE,
        "summary": {},
        "global_checks": global_checks(),
        "new_cases": new,
        "old_cases": old_rows(),
        "mutation_controls": mutation_rows(),
    }
    checks = (
        doc["global_checks"]
        + [c for r in doc["new_cases"] for c in r["checks"]]
        + [c for r in doc["old_cases"] for c in r["checks"]]
        + [c for r in doc["mutation_controls"] for c in r["checks"]]
    )
    graded = [c for c in checks if c["result"] in ("PASS", "FAIL")]
    findings = [c for c in graded if c["result"] != c["predicted"]]
    invalid = [r["id"] for r in doc["mutation_controls"] if r["changes_text"] != (r["id"] != "M00")]
    doc["summary"] = {
        "checks": len(graded),
        "pass": sum(c["result"] == "PASS" for c in graded),
        "fail": sum(c["result"] == "FAIL" for c in graded),
        "fail, predicted (kept)": sum(c["result"] == "FAIL" == c["predicted"] for c in graded),
        "findings (result differs from prediction)": len(findings),
        "not applicable (old raw_region checks after R2)": sum(c["result"] == "NOT_APPLICABLE" for c in checks),
        "invalid mutations": invalid,
    }
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "results.json").write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    (out_dir / "summary.md").write_text(summary_md(doc["environment"], doc), encoding="utf-8", newline="\n")
    print(json.dumps(doc["environment"], indent=2))
    for row in doc["new_cases"]:
        o = row["output"]
        print(f"{row['case']} {row['helper']:8} reasons={o['reasons']} status={o['status']}")
    for row in doc["old_cases"]:
        failed = [c["check"] for c in row["checks"] if c["result"] == "FAIL"]
        print(f"{row['case']} repaired reasons={row['output']['reasons']} failed={failed}")
    for r in doc["mutation_controls"]:
        print(f"{r['id']} {r['what']}: repaired {r['repaired']['observed']}, baseline {r['baseline']['observed']}")
    print(json.dumps(doc["summary"], indent=2))
    for c in checks:
        if c["result"] == "FAIL":
            tag = "FINDING" if c in findings else "FAIL (predicted, kept)"
            print(f"  {tag}: {c['check']} -> {json.dumps(c['detail'], ensure_ascii=False)[:200]}")
    for c in findings:
        if c["result"] == "PASS":
            print(f"  FINDING (passed, predicted to fail): {c['check']}")
    return 1 if findings or invalid else 0


if __name__ == "__main__":
    sys.exit(main())
